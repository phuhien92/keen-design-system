// Loads canonical DTCG token files into a flat, validated token list.
// Canvas tokens color the design file's annotations and frames. They reach Pen only, never the CSS or the typed map.
export type Tier = "primitive" | "semantic" | "component" | "canvas";

export interface Source {
  file: string;
  tier: Tier;
  json: unknown;
}

export interface Token {
  name: string;
  path: string[];
  tier: Tier;
  file: string;
  type: string;
  // Authored $value per mode. "light" is the DTCG $value; other modes come from $extensions.keen.modes.
  values: Record<string, unknown>;
  description?: string;
  keen: Record<string, unknown>;
}

export interface Issue {
  rule: string;
  token: string;
  message: string;
}

export const modes = ["light", "dark"] as const;
export const types = new Set(["color", "dimension", "number", "fontFamily", "fontWeight", "duration", "cubicBezier", "transition"]);
// Leading segments that name a token category rather than a component.
export const categories = new Set(["color", "space", "radius", "font", "motion", "icon", "canvas"]);
const groupKeys = new Set(["$type", "$description", "$extensions", "$schema", "$deprecated"]);
const tokenKeys = new Set(["$value", "$type", "$description", "$extensions", "$deprecated"]);
const segment = /^[a-z0-9]+(-[a-z0-9]+)*$/;

export const cssVar = (name: string) => `--keen-${name.replaceAll(".", "-")}`;
export const isReference = (value: unknown): value is string => typeof value === "string" && /^\{[^{}]+\}$/.test(value);
export const referenceName = (value: string) => value.slice(1, -1);

const isObject = (value: unknown): value is Record<string, unknown> => typeof value === "object" && value !== null && !Array.isArray(value);

export function loadTokens(sources: Source[]): { tokens: Token[]; issues: Issue[] } {
  const tokens: Token[] = [];
  const issues: Issue[] = [];
  for (const source of sources) {
    if (!isObject(source.json)) {
      issues.push({ rule: "schema", token: source.file, message: "is not a JSON object" });
      continue;
    }
    walk(source, source.json, [], undefined, tokens, issues);
  }
  const byVar = new Map<string, string>();
  for (const token of tokens) {
    const name = cssVar(token.name);
    const other = byVar.get(name);
    if (other) issues.push({ rule: "duplicate", token: token.name, message: `generates ${name}, already generated by ${other}` });
    byVar.set(name, token.name);
  }
  return { tokens, issues };
}

function walk(source: Source, node: Record<string, unknown>, path: string[], inherited: string | undefined, out: Token[], issues: Issue[]) {
  const type = typeof node.$type === "string" ? node.$type : inherited;
  if ("$value" in node) {
    out.push(toToken(source, node, path, type, issues));
    return;
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith("$")) {
      if (!groupKeys.has(key)) issues.push({ rule: "schema", token: [...path, key].join("."), message: "is not a DTCG group property" });
      continue;
    }
    if (!isObject(child)) {
      issues.push({ rule: "schema", token: [...path, key].join("."), message: "is neither a token nor a group" });
      continue;
    }
    walk(source, child, [...path, key], type, out, issues);
  }
}

function toToken(source: Source, node: Record<string, unknown>, path: string[], type: string | undefined, issues: Issue[]): Token {
  const name = path.join(".");
  const report = (rule: string, message: string) => issues.push({ rule, token: name, message });
  for (const key of Object.keys(node)) if (!tokenKeys.has(key)) report("schema", `has unknown property ${key}`);
  for (const part of path) if (!segment.test(part)) report("naming", `segment "${part}" is not lowercase kebab-case`);
  const tier = path[0] === "canvas" ? "canvas" : path[1] === "primitive" || path[1] === "semantic" ? path[1] : "component";
  if (tier !== source.tier) report("tier", `has tier ${tier} but is authored in ${source.file}, which holds ${source.tier} tokens`);
  if (tier === "component" && (path.length < 2 || categories.has(path[0]))) {
    report("tier", "has no tier segment: use category.primitive.*, category.semantic.*, or component.*");
  }
  if (!type || !types.has(type)) report("type", `has no resolvable DTCG $type (got ${JSON.stringify(type)})`);
  const description = typeof node.$description === "string" ? node.$description.trim() : undefined;
  if (tier !== "primitive" && !description) report("description", "needs a $description stating its intended use");
  const extensions = isObject(node.$extensions) ? node.$extensions : {};
  const keen = isObject(extensions.keen) ? extensions.keen : {};
  const values: Record<string, unknown> = { light: node.$value };
  if (keen.modes !== undefined) {
    if (!isObject(keen.modes)) report("schema", "$extensions.keen.modes must be an object");
    else {
      for (const [mode, value] of Object.entries(keen.modes)) {
        if (mode === "light" || !(modes as readonly string[]).includes(mode)) report("schema", `has unknown mode ${mode}`);
        else values[mode] = value;
      }
    }
  }
  if (keen.lifecycle === "deprecated" && typeof keen.replacement !== "string") {
    report("schema", "is deprecated without $extensions.keen.replacement");
  }
  for (const [mode, value] of Object.entries(values)) {
    const problem = type && types.has(type) ? checkValue(type, value) : undefined;
    if (problem) report("value", `${mode} value ${problem}`);
  }
  return { name, path, tier, file: source.file, type: type ?? "", values, description, keen };
}

const finite = (value: unknown): value is number => typeof value === "number" && Number.isFinite(value);

// Returns a problem description, or undefined when the value is valid for the type. References are checked by the resolver.
export function checkValue(type: string, value: unknown): string | undefined {
  if (isReference(value)) return undefined;
  switch (type) {
    case "color": {
      if (!isObject(value) || value.colorSpace !== "srgb") return "must be an srgb color object";
      const c = value.components;
      if (!Array.isArray(c) || c.length !== 3 || !c.every((n) => finite(n) && n >= 0 && n <= 1))
        return "must have three components between 0 and 1";
      if (typeof value.hex !== "string" || !/^#[0-9A-F]{6}$/.test(value.hex)) return "must carry an uppercase #RRGGBB hex";
      const hex = value.hex;
      const matches = c.every((n, i) => Math.round(n * 255) === Number.parseInt(hex.slice(1 + i * 2, 3 + i * 2), 16));
      return matches ? undefined : `components do not match hex ${hex}`;
    }
    case "dimension":
      if (!isObject(value) || !finite(value.value)) return "must be { value, unit }";
      return value.unit === "px" || value.unit === "rem"
        ? undefined
        : `has unit ${JSON.stringify(value.unit)}; allowed units are px and rem`;
    case "duration":
      if (!isObject(value) || !finite(value.value) || value.value < 0) return "must be { value, unit } with a non-negative value";
      return value.unit === "ms" || value.unit === "s" ? undefined : `has unit ${JSON.stringify(value.unit)}; allowed units are ms and s`;
    case "number":
      return finite(value) ? undefined : "must be a number";
    case "fontFamily":
      if (typeof value === "string" && value) return undefined;
      return Array.isArray(value) && value.length > 0 && value.every((f) => typeof f === "string" && f)
        ? undefined
        : "must be a name or a list of names";
    case "fontWeight":
      return finite(value) && value >= 1 && value <= 1000 ? undefined : "must be a number from 1 to 1000";
    case "cubicBezier":
      return Array.isArray(value) &&
        value.length === 4 &&
        value.every(finite) &&
        value[0] >= 0 &&
        value[0] <= 1 &&
        value[2] >= 0 &&
        value[2] <= 1
        ? undefined
        : "must be four numbers with x values between 0 and 1";
    case "transition": {
      if (!isObject(value)) return "must be { duration, delay, timingFunction }";
      return (
        checkValue("duration", value.duration) ?? checkValue("duration", value.delay) ?? checkValue("cubicBezier", value.timingFunction)
      );
    }
    default:
      return `has unsupported type ${type}`;
  }
}
